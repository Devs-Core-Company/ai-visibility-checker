/**
 * Live fetches as AI crawlers versus a browser.
 *
 * robots.txt says what a site asks bots to do; this says what the site's
 * server, CDN and firewall actually do when a bot turns up. Two passes:
 *
 * 1. The start URL as a browser and as every fetching bot in AI_BOTS.
 * 2. A sample of key pages (the most-linked) as a browser and four bots from
 *    different operators, so blocking that only applies to deeper paths
 *    (a WAF rule on /blog/*, a paywall, a geo rule) is caught too.
 *
 * Results: site.botFetches + site.browserFetch (contract), and full responses
 * kept in module WeakMaps for checks that compare bodies.
 */
import type { BotFetchResult, FetchResult, SiteContext } from '../core/types.js';
import { countWords, mapLimit, roughText, topLinkedPages } from '../checks/_ai-util.js';
import { BROWSER_UA, botByToken, fetchingBots, type AiBot } from './bots.js';

/** Never more than three requests in flight to the audited site. */
const CONCURRENCY = 3;
const TIMEOUT_MS = 15_000;
const MAX_BYTES = 3 * 1024 * 1024;
const SAMPLE_PAGES = 5;
const SAMPLE_BOTS = ['GPTBot', 'OAI-SearchBot', 'Claude-User', 'PerplexityBot'];

export interface SampleBotFetch {
  url: string;
  browser: { status: number; words: number; challenge: string | null; ms: number; error?: string };
  bots: BotFetchResult[];
}

const fullResults = new WeakMap<SiteContext, Map<string, FetchResult>>();
const samples = new WeakMap<SiteContext, SampleBotFetch[]>();

/** Full response a bot received for the start URL (body included). */
export function botFetchDetail(site: SiteContext, token: string): FetchResult | undefined {
  return fullResults.get(site)?.get(token.toLowerCase());
}

/** Key-page sample results, or undefined when fetchAsBots has not run for this site. */
export function sampleBotFetches(site: SiteContext): SampleBotFetch[] | undefined {
  return samples.get(site);
}

/** Test seam: attach sample results to a hand-built site. */
export function setSampleBotFetches(site: SiteContext, data: SampleBotFetch[]): void {
  samples.set(site, data);
}

// ---------------------------------------------------------------------------
// Challenge detection
// ---------------------------------------------------------------------------

/**
 * Name the bot-protection product when a response is an interstitial or block
 * page rather than the site. Header markers first (reliable), then body markers.
 */
export function detectChallenge(
  status: number,
  headers: Record<string, string>,
  body: string,
): string | null {
  const h = (k: string) => (headers[k] ?? '').toLowerCase();
  if (h('cf-mitigated').includes('challenge')) return 'cloudflare';
  if (h('x-vercel-mitigated').includes('challenge') || h('x-vercel-challenge-token'))
    return 'vercel';
  if (headers['x-datadome'] || headers['x-dd-b'] || h('set-cookie').includes('datadome=')) {
    if (status >= 400 || /captcha-delivery\.com/i.test(body)) return 'datadome';
  }
  if (h('x-iinfo') || h('set-cookie').includes('incap_ses')) {
    if (status >= 400 || /_Incapsula_Resource|Incapsula incident/i.test(body)) return 'imperva';
  }
  if (h('x-sucuri-block') || (h('server').includes('sucuri') && status >= 400)) return 'sucuri';
  if (h('server').includes('akamaighost') && status === 403) return 'akamai';
  if (h('x-amzn-waf-action') === 'captcha' || h('x-amzn-waf-action') === 'challenge')
    return 'aws-waf';

  const head = body.slice(0, 30_000);
  if (
    /<title>\s*Just a moment\.{3}\s*<\/title>/i.test(head) ||
    /\/cdn-cgi\/challenge-platform\//i.test(head) ||
    /cf-chl-/i.test(head)
  )
    return 'cloudflare';
  if (/Attention Required! \| Cloudflare/i.test(head) || /cf-error-details/i.test(head))
    return 'cloudflare';
  if (/Vercel Security Checkpoint/i.test(head)) return 'vercel';
  if (/_Incapsula_Resource|Incapsula incident ID/i.test(head)) return 'imperva';
  if (/captcha-delivery\.com|geo\.captcha-delivery/i.test(head)) return 'datadome';
  if (/px-captcha|_pxCaptcha|perimeterx|human security/i.test(head) && status >= 400)
    return 'perimeterx';
  if (status === 403 && /Access Denied[\s\S]{0,600}Reference\s*#[\d.a-f]+/i.test(head))
    return 'akamai';
  if (/sucuri-firewall|Sucuri WebSite Firewall|Access Denied - Sucuri/i.test(head)) return 'sucuri';
  if (/awswaf|aws-waf-token/i.test(head) && status >= 400) return 'aws-waf';
  if (/Wordfence|generated by Wordfence/i.test(head) && status >= 400) return 'wordfence';
  if (
    /Anubis|within\.website\/x\/cmd\/anubis/i.test(head) &&
    /proof-of-work|making sure you'?re not a bot/i.test(head)
  )
    return 'anubis';
  if (
    (status >= 400 || countWords(roughText(head)) < 150) &&
    /(g-recaptcha|hcaptcha\.com\/1\/api|challenges\.cloudflare\.com\/turnstile|verify you are (a )?human|are you a robot|complete the security check)/i.test(
      head,
    )
  )
    return 'captcha';
  return null;
}

// ---------------------------------------------------------------------------
// Verdicts
// ---------------------------------------------------------------------------

const BLOCKING = new Set([401, 403, 405, 406, 407, 409, 418, 429, 451, 503]);

interface Shot {
  status: number;
  words: number;
  challenge: string | null;
  error?: string;
  finalUrl?: string;
}

function okShot(s: Shot): boolean {
  return !s.error && s.status >= 200 && s.status < 300 && !s.challenge;
}

/** Compare a bot's response with the browser baseline. */
export function verdictFor(bot: Shot, browser: Shot): BotFetchResult['verdict'] {
  const browserOk = okShot(browser);
  if (bot.error) return browserOk ? 'error' : 'inconclusive';
  if (!browserOk) return okShot(bot) ? 'ok' : 'inconclusive';
  if (bot.challenge || BLOCKING.has(bot.status) || bot.status >= 400 || bot.status === 0)
    return 'blocked';
  if (bot.status >= 300 && bot.status < 400) return 'differs';
  if (browser.words >= 80 && bot.words < browser.words * 0.5) return 'differs';
  return 'ok';
}

function shotOf(res: FetchResult): Shot {
  const words = countWords(roughText(res.body || ''));
  return {
    status: res.status,
    words,
    challenge:
      res.status === 0 ? null : detectChallenge(res.status, res.headers ?? {}, res.body || ''),
    error: res.error,
    finalUrl: res.finalUrl,
  };
}

async function get(
  site: SiteContext,
  url: string,
  ua: string,
): Promise<{ res: FetchResult; ms: number }> {
  const started = Date.now();
  try {
    const res = await site.fetcher.fetch(url, {
      userAgent: ua,
      timeoutMs: Math.min(site.options?.timeoutMs ?? TIMEOUT_MS, TIMEOUT_MS),
      maxBytes: MAX_BYTES,
      headers: { accept: 'text/html,application/xhtml+xml,application/xml;q=0.9,*/*;q=0.8' },
    });
    return { res, ms: Date.now() - started };
  } catch (e) {
    const err = e instanceof Error ? e.message : String(e);
    return {
      res: {
        url,
        finalUrl: url,
        status: 0,
        ok: false,
        headers: {},
        redirects: [],
        body: '',
        bytes: 0,
        truncated: false,
        contentType: '',
        ttfbMs: 0,
        totalMs: Date.now() - started,
        error: err,
      },
      ms: Date.now() - started,
    };
  }
}

function toResult(bot: AiBot, res: FetchResult, ms: number, browser: Shot): BotFetchResult {
  const shot = shotOf(res);
  let verdict = verdictFor(shot, browser);
  // Sent somewhere else entirely (a block page on another path or host).
  if (verdict === 'ok' && browser.finalUrl && res.finalUrl && res.finalUrl !== browser.finalUrl) {
    try {
      const a = new URL(res.finalUrl);
      const b = new URL(browser.finalUrl);
      if (a.host !== b.host || a.pathname !== b.pathname) verdict = 'differs';
    } catch {
      /* keep */
    }
  }
  return {
    token: bot.token,
    operator: bot.operator,
    purpose: bot.purpose,
    status: res.status,
    bytes: res.bytes,
    words: shot.words,
    challenge: shot.challenge,
    verdict,
    ms,
    ...(res.error ? { error: res.error } : {}),
  };
}

/**
 * Fetch the start URL as a browser and as every AI bot that fetches, then a
 * sample of key pages as four bots. Fills site.browserFetch and site.botFetches.
 * Never throws.
 */
export async function fetchAsBots(site: SiteContext): Promise<void> {
  const url = site.startUrl;
  const store = new Map<string, FetchResult>();
  fullResults.set(site, store);

  const browser = await get(site, url, BROWSER_UA);
  site.browserFetch = browser.res;
  const browserShot = shotOf(browser.res);

  const bots = fetchingBots();
  const results = await mapLimit(bots, CONCURRENCY, async (bot) => {
    const { res, ms } = await get(site, url, bot.ua!);
    store.set(bot.token.toLowerCase(), res);
    return toResult(bot, res, ms, browserShot);
  });
  site.botFetches = results;

  // Key-page sample.
  const pages = topLinkedPages(site, SAMPLE_PAGES)
    .map((p) => p.finalUrl || p.url)
    .filter((u) => u !== url && u !== browser.res.finalUrl);
  const sampleBots = SAMPLE_BOTS.map((t) => botByToken(t)).filter((b): b is AiBot =>
    Boolean(b?.ua),
  );
  const sample: SampleBotFetch[] = [];
  await mapLimit(pages, 1, async (pageUrl) => {
    const b = await get(site, pageUrl, BROWSER_UA);
    const bShot = shotOf(b.res);
    const botResults = await mapLimit(sampleBots, CONCURRENCY, async (bot) => {
      const { res, ms } = await get(site, pageUrl, bot.ua!);
      return toResult(bot, res, ms, bShot);
    });
    sample.push({
      url: pageUrl,
      browser: {
        status: b.res.status,
        words: bShot.words,
        challenge: bShot.challenge,
        ms: b.ms,
        ...(b.res.error ? { error: b.res.error } : {}),
      },
      bots: botResults,
    });
  });
  samples.set(site, sample);
}
