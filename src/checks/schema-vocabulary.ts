/** Type name → direct parent types. */
export const SCHEMA_TYPES: ReadonlyMap<string, readonly string[]> = new Map(
  RAW.split(/\s+/)
    .filter(Boolean)
    .map((e) => {
      const [name, parents] = e.split(':');
      return [name!, parents ? parents.split(',') : []] as const;
    }),
);

/** True when `type` is a schema.org type. */
export function isSchemaType(type: string): boolean {
  return SCHEMA_TYPES.has(type);
}

/** True when `type` is `ancestor` or one of its subtypes. */
export function isSubtypeOf(type: string, ancestor: string): boolean {
  const seen = new Set<string>();
  const walk = (t: string): boolean => {
    if (t === ancestor) return true;
    if (seen.has(t)) return false;
    seen.add(t);
    return (SCHEMA_TYPES.get(t) ?? []).some(walk);
  };
  return walk(type);
}
